// Writes supabase/migrations/033_singapore_maths.sql from server/sgmath/strings-seed.js
// (TUT-43). Run after editing a string:
//   node scripts/sgmath-migration.mjs
// tests/unit/sgmath-core.test.js fails when the committed SQL is out of step.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { LANGUAGES, STRINGS } from '../server/sgmath/strings-seed.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MIGRATION = path.join(ROOT, 'supabase', 'migrations', '033_singapore_maths.sql');

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

const SCHEMA = `-- 033: Singapore Maths Method (TUT-43, docs/specs/TUT-43-singapore-maths.md).
-- GENERATED by scripts/sgmath-migration.mjs from server/sgmath/strings-seed.js; edit those, then rerun.
-- Run once in the Supabase SQL editor. Safe to run twice (re-running updates the seeded strings).
-- No existing table is changed. Every table is read and written only with the service-role key.
--
-- Problems are not stored: they are built in code from (type, grade, difficulty, index),
-- with the answer computed from the same numbers (server/sgmath/core.js). Their words are
-- string rows below (keys tpl.*), so a new language is rows only.

create table if not exists sgmath_languages (
  code text primary key check (code ~ '^[a-z]{2,3}$'),
  label text not null,
  script text not null,
  enabled boolean not null default true,
  sort smallint not null default 100
);

create table if not exists sgmath_strings (
  lang text not null references sgmath_languages(code) on delete cascade,
  key text not null,
  text text not null,
  updated_at timestamptz not null default now(),
  primary key (lang, key)
);

create table if not exists sgmath_sessions (
  id uuid primary key default gen_random_uuid(),
  family_id bigint not null references family_registrations(id),
  student_id uuid not null references students(id),
  focus_model_type text,
  diagnostic boolean not null default false,
  gate text not null check (gate in ('max', 'free_weekly')),
  week_start date,
  status text not null default 'open' check (status in ('open', 'completed', 'abandoned')),
  language text not null default 'en',
  problems jsonb not null,
  concrete text check (concrete in ('done', 'skipped')),
  concrete_viewer_key text,
  ai_hints_used smallint not null default 0,
  started_at timestamptz not null default now(),
  pictorial_started_at timestamptz,
  completed_at timestamptz
);
-- One free session per child per IST week: the second one fails this index (409 free_used).
create unique index if not exists sgmath_sessions_free_week on sgmath_sessions (student_id, week_start) where gate = 'free_weekly' and week_start is not null;
create index if not exists sgmath_sessions_student on sgmath_sessions (student_id, started_at);

create table if not exists sgmath_attempts (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null references sgmath_sessions(id) on delete cascade,
  student_id uuid not null references students(id),
  problem_id text not null,
  problem_index smallint not null,
  model_type text not null,
  difficulty smallint not null,
  step text not null check (step in ('pictorial', 'abstract')),
  correct boolean not null default false,
  done boolean not null default false,
  tries smallint not null default 0,
  hint_used boolean not null default false,
  built_spec jsonb,
  ms integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (session_id, problem_index, step)
);
create index if not exists sgmath_attempts_session on sgmath_attempts (session_id);
create index if not exists sgmath_attempts_student on sgmath_attempts (student_id, created_at);

alter table sgmath_languages enable row level security;
alter table sgmath_strings enable row level security;
alter table sgmath_sessions enable row level security;
alter table sgmath_attempts enable row level security;
`;

export function buildSql() {
  let sql = SCHEMA + '\n-- Seeded languages and strings.\n';
  for (const l of LANGUAGES) {
    sql += `insert into sgmath_languages (code, label, script, enabled, sort) values (${q(l.code)}, ${q(l.label)}, ${q(l.script)}, ${l.enabled}, ${l.sort})\n  on conflict (code) do update set label = excluded.label, script = excluded.script, sort = excluded.sort;\n`;
  }
  for (const l of LANGUAGES) {
    const rows = Object.entries(STRINGS[l.code]).sort(([a], [b]) => a.localeCompare(b));
    sql += `\ninsert into sgmath_strings (lang, key, text) values\n`;
    sql += rows.map(([k, v]) => `  (${q(l.code)}, ${q(k)}, ${q(v)})`).join(',\n');
    sql += `\non conflict (lang, key) do update set text = excluded.text, updated_at = now();\n`;
  }
  return sql;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(MIGRATION, buildSql());
  console.log('wrote', path.relative(ROOT, MIGRATION));
}
