function withPeople(lang, table) {
  const out = { ...table };
  NAMES[lang].forEach((n, i) => { out['name.' + (i + 1)] = n; });
  for (const [k, v] of Object.entries(ITEMS[lang])) out['item.' + k] = v;
  return out;
}

